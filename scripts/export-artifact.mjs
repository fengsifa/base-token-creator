#!/usr/bin/env node
/**
 * Copy the compiled TokenFactory artifact into lib/ so the frontend can deploy
 * the factory from the browser without needing Hardhat at runtime.
 *
 * The checked-in `lib/tokenfactory-artifact.json` is what `/setup` uses. Keep it
 * in sync by running `npm run contracts:build` after any change to the contract.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const artifactPath = path.join(
  root,
  "artifacts",
  "contracts",
  "TokenFactory.sol",
  "TokenFactory.json",
);
const outputPath = path.join(root, "lib", "tokenfactory-artifact.json");

const EIP170_LIMIT = 24_576;

/**
 * Hardhat's artifact `metadata` field is not always populated, so the compiler
 * version is read from the build-info file, which always has it.
 */
async function readCompilerVersion() {
  try {
    const directory = path.join(root, "artifacts", "build-info");
    const entries = await readdir(directory);
    for (const entry of entries) {
      if (!entry.endsWith(".json") || entry.endsWith(".output.json")) continue;
      const info = JSON.parse(await readFile(path.join(directory, entry), "utf8"));
      const version = info.solcLongVersion ?? info.solcVersion;
      if (version) return String(version);
    }
  } catch {
    // build-info is optional; a missing version must not fail the export
  }
  return "unknown";
}

async function main() {
  let artifact;
  try {
    artifact = JSON.parse(await readFile(artifactPath, "utf8"));
  } catch (error) {
    console.error(`Could not read ${artifactPath}.`);
    console.error("Run `npx hardhat compile` first.");
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }

  const bytecode = artifact.bytecode ?? "0x";
  if (bytecode === "0x") {
    console.error("The compiled artifact contains no creation bytecode.");
    process.exit(1);
  }

  let compiler = "unknown";
  try {
    compiler = JSON.parse(artifact.metadata).compiler.version;
  } catch {
    // metadata is optional; fall back to build-info below
  }
  if (compiler === "unknown") compiler = await readCompilerVersion();

  const output = {
    _comment:
      "Generated by `npm run sync:artifact` from the hardhat compile output. Do not edit by hand.",
    contractName: artifact.contractName,
    sourceName: artifact.sourceName,
    compiler,
    abi: artifact.abi,
    bytecode,
    deployedBytecode: artifact.deployedBytecode ?? "0x",
  };

  await writeFile(outputPath, `${JSON.stringify(output, null, 2)}\n`, "utf8");

  const size = (bytecode.length - 2) / 2;
  console.log(`Wrote ${path.relative(root, outputPath)}`);
  console.log(`  contract         : ${output.contractName} (solc ${compiler})`);
  console.log(`  creation bytecode: ${size} bytes`);
  console.log(`  ABI entries      : ${output.abi.length}`);

  if (size > EIP170_LIMIT) {
    console.error(`Bytecode exceeds the EIP-170 limit of ${EIP170_LIMIT} bytes.`);
    process.exit(1);
  }
}

await main();
