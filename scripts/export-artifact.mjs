#!/usr/bin/env node
/**
 * Copy compiled artifacts into lib/ so the frontend can deploy and call the
 * factories from the browser without needing Hardhat at runtime.
 *
 * Two outputs, on purpose:
 *
 *  - `lib/tokenfactory-artifact.json` — the ORIGINAL, feature-less factory. It is
 *    still the source of truth for the instance already deployed on Base Sepolia,
 *    which `scripts/verify-live-factory.mjs` checks byte for byte, so its shape
 *    must not change.
 *  - `lib/tokenfactory-v2-artifact.json` — the two factories that create tokens
 *    with Burnable / Mintable / Pausable. `/setup` deploys these.
 *
 * Run `npm run contracts:build` after any change to a contract.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const EIP170_LIMIT = 24_576;

/**
 * Hardhat's artifact `metadata` field is not always populated, so the compiler
 * version is read from the build-info file, which always has it.
 */
async function readCompilerVersion() {
  try {
    const directory = path.join(root, "artifacts", "build-info");
    const entries = await readdir(directory);
    for (const entry of entries) {
      if (!entry.endsWith(".json") || entry.endsWith(".output.json")) continue;
      const info = JSON.parse(await readFile(path.join(directory, entry), "utf8"));
      const version = info.solcLongVersion ?? info.solcVersion;
      if (version) return String(version);
    }
  } catch {
    // build-info is optional; a missing version must not fail the export
  }
  return "unknown";
}

async function loadArtifact(sourceName, contractName) {
  const artifactPath = path.join(root, "artifacts", "contracts", sourceName, `${contractName}.json`);
  let artifact;
  try {
    artifact = JSON.parse(await readFile(artifactPath, "utf8"));
  } catch (error) {
    console.error(`Could not read ${artifactPath}.`);
    console.error("Run `npx hardhat compile` first.");
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }

  const bytecode = artifact.bytecode ?? "0x";
  if (bytecode === "0x") {
    console.error(`${contractName} has no creation bytecode; the build is incomplete.`);
    process.exit(1);
  }
  return artifact;
}

async function resolveCompiler(artifact) {
  let compiler = "unknown";
  try {
    compiler = JSON.parse(artifact.metadata).compiler.version;
  } catch {
    // metadata is optional; fall back to build-info below
  }
  if (compiler === "unknown") compiler = await readCompilerVersion();
  return compiler;
}

function assertFitsLimit(contractName, bytecode) {
  const size = (bytecode.length - 2) / 2;
  if (size > EIP170_LIMIT) {
    console.error(
      `${contractName} runtime bytecode is ${size} bytes, over the EIP-170 limit of ${EIP170_LIMIT}.`,
    );
    process.exit(1);
  }
  return size;
}

async function main() {
  // ---------------------------------------------------------------------------
  // 1. The original factory, unchanged shape (see the note at the top).
  // ---------------------------------------------------------------------------
  const legacy = await loadArtifact("TokenFactory.sol", "TokenFactory");
  const legacyCompiler = await resolveCompiler(legacy);

  await writeFile(
    path.join(root, "lib", "tokenfactory-artifact.json"),
    `${JSON.stringify(
      {
        _comment:
          "Generated by `npm run sync:artifact` from the hardhat compile output. Do not edit by hand.",
        contractName: legacy.contractName,
        sourceName: legacy.sourceName,
        compiler: legacyCompiler,
        abi: legacy.abi,
        bytecode: legacy.bytecode ?? "0x",
        deployedBytecode: legacy.deployedBytecode ?? "0x",
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
  const legacySize = assertFitsLimit("TokenFactory", legacy.bytecode);
  console.log("Wrote lib/tokenfactory-artifact.json");
  console.log(`  contract         : ${legacy.contractName} (solc ${legacyCompiler})`);
  console.log(`  creation bytecode: ${legacySize} bytes`);

  // ---------------------------------------------------------------------------
  // 2. The two feature factories.
  //
  // Both are exported together because they are deployed together and must be
  // kept in step: a page that shows Burnable as available sends the user to the
  // burnable factory, and if only one address were configured the option would
  // fail at the last step.
  // ---------------------------------------------------------------------------
  const core = await loadArtifact("TokenFactoryV2.sol", "TokenFactoryCore");
  const burnable = await loadArtifact("TokenFactoryV2.sol", "TokenFactoryBurnable");
  const v2Compiler = await resolveCompiler(core);

  const coreSize = assertFitsLimit("TokenFactoryCore", core.bytecode);
  const burnableSize = assertFitsLimit("TokenFactoryBurnable", burnable.bytecode);

  await writeFile(
    path.join(root, "lib", "tokenfactory-v2-artifact.json"),
    `${JSON.stringify(
      {
        _comment:
          "Generated by `npm run sync:artifact` from the hardhat compile output. Do not edit by hand.",
        compiler: v2Compiler,
        sourceName: core.sourceName,
        factories: {
          core: {
            contractName: core.contractName,
            abi: core.abi,
            bytecode: core.bytecode,
            deployedBytecode: core.deployedBytecode ?? "0x",
          },
          burnable: {
            contractName: burnable.contractName,
            abi: burnable.abi,
            bytecode: burnable.bytecode,
            deployedBytecode: burnable.deployedBytecode ?? "0x",
          },
        },
      },
      null,
      2,
    )}\n`,
    "utf8",
  );

  console.log("Wrote lib/tokenfactory-v2-artifact.json");
  console.log(`  compiler         : solc ${v2Compiler}`);
  console.log(`  core             : ${coreSize} bytes (limit ${EIP170_LIMIT})`);
  console.log(`  burnable         : ${burnableSize} bytes (limit ${EIP170_LIMIT})`);
  console.log(`  ABI entries      : ${core.abi.length} each (identical by construction)`);
}

await main();
